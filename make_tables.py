r"""Build thesis tables from out/results.json.

    .venv\Scripts\python.exe make_tables.py            # English (thesis language)
    .venv\Scripts\python.exe make_tables.py --lang zh  # Chinese working copy

Writes out/tables_en.md (or out/tables_zh.md) and prints the same content.
"""

from __future__ import annotations

import argparse
import json
import math
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "out"

DISPLAY = {"claude": "Claude", "chatgpt": "ChatGPT", "gemini": "Gemini"}

L = {
    "en": {
        "title": "# Result tables (auto-generated by make_tables.py)",
        "t1": "## Table 1. Aggregate metrics by model and prompt condition",
        "t1_head": ("| Model | Cond. | Artifacts | Exec. | Exec. rate | Tests | Passed | "
                    "Pass rate [95% CI] | Imported target | Mean coverage (a) | Coverage yield (b) |"),
        "note1": "(a) Averaged over artifacts that successfully imported the target module only.",
        "note2": ("(b) Sum of covered lines over all artifacts (non-imported count as 0) divided by the "
                  "module's total statements; not affected by excluding failed artifacts."),
        "t2": "## Table 2. Coverage yield per module (%)",
        "t3": "## Table 3. Failure modes per artifact",
        "t3_head": "| Model / cond. |",
        "t4": "## Table 4. Failure details (all except \"no failure\")",
        "t4_head": "| Model | Cond. | Module | Category | Detail |",
        "cols": ("Model", "Cond.", "Module", "Category", "Detail"),
        "none": "no failure",
        "assert": "assertion failure",
        "import": "import failure",
        "hang": "hang / infinite loop",
        "syntax": "syntax / truncation",
        "other": "other collection error",
        "cond": {"A": "A (underspec.)", "B": "B (specified)"},
        "outfile": "tables_en.md",
    },
    "zh": {
        "title": "# 结果表（由 make_tables.py 自动生成）",
        "t1": "## 表 1 模型 × 条件总体指标",
        "t1_head": ("| 模型 | 条件 | 产物数 | 可执行 | 可执行率 | 测试数 | 通过 | "
                    "通过率 [95% CI] | 导入目标 | 覆盖率均值† | 覆盖率产出‡ |"),
        "note1": "† 仅在成功导入目标模块的产物上取平均。",
        "note2": ("‡ 全部产物（未导入按 0 计）的覆盖行数之和 ÷ 该模块总语句数；"
                  "不受“失败产物被排除”影响。"),
        "t2": "## 表 2 逐模块覆盖率产出（%）",
        "t3": "## 表 3 失败模式分布（按产物计）",
        "t3_head": "| 模型 / 条件 |",
        "t4": "## 表 4 失败详情（非“无失败”）",
        "t4_head": "| 模型 | 条件 | 模块 | 类别 | 详情 |",
        "cols": ("模型", "条件", "模块", "类别", "详情"),
        "none": "无失败",
        "assert": "断言失败",
        "import": "导入失败（模块名错误）",
        "hang": "挂起/死循环",
        "syntax": "语法错误（截断）",
        "other": "收集阶段其他错误",
        "cond": {"A": "A（模糊）", "B": "B（明确）"},
        "outfile": "tables_zh.md",
    },
}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, centre - half), min(1.0, centre + half))


def fmt(x: float | None, digits: int = 1) -> str:
    return "—" if x is None else f"{x:.{digits}f}%"


def classify(r: dict, t: dict) -> str:
    kind = r["failure_kind"]
    detail = r.get("failure_detail") or ""
    if kind == "none":
        return t["none"]
    if kind == "timeout":
        return t["hang"]
    if kind == "collection_error":
        if "ModuleNotFoundError" in detail or "ImportError" in detail:
            return t["import"]
        if "SyntaxError" in detail or "IndentationError" in detail:
            return t["syntax"]
        return t["other"]
    if kind == "assertion_failure":
        return t["assert"]
    return kind


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lang", choices=["en", "zh"], default="en")
    args = ap.parse_args()
    t = L[args.lang]

    data = json.loads((OUT / "results.json").read_text(encoding="utf-8"))
    rows = data["results"]

    module_statements: dict[str, int] = {}
    for r in rows:
        if r.get("statements"):
            module_statements.setdefault(r["module"], r["statements"])

    groups = defaultdict(list)
    for r in rows:
        groups[(r["model"], r["condition"])].append(r)

    lines: list[str] = []
    add = lines.append

    add(t["title"])
    add("")
    add(t["t1"])
    add("")
    add(t["t1_head"])
    add("|---|---|---|---|---|---|---|---|---|---|---|")
    for (model, cond), rs in sorted(groups.items()):
        n = len(rs)
        exec_n = sum(1 for r in rs if (r["collected"] or 0) > 0)
        tests = sum(r["collected"] or 0 for r in rs)
        passed = sum(r["passed"] or 0 for r in rs)
        imported = sum(1 for r in rs if r["target_imported"])
        covered = [r for r in rs if r["target_imported"]]
        cov = sum(r["coverage_pct"] for r in covered) / len(covered) if covered else None
        tot_stmt = sum((r["statements"] or module_statements.get(r["module"], 0)) for r in rs)
        tot_cov = sum(r["covered_lines"] or 0 for r in rs)
        yield_pct = 100 * tot_cov / tot_stmt if tot_stmt else None
        lo, hi = wilson(passed, tests)
        add(
            f"| {DISPLAY[model]} | {t['cond'][cond]} | {n} | {exec_n} | {exec_n/n:.0%} | {tests} | "
            f"{passed} | {fmt(100*passed/tests if tests else None)} "
            f"[{lo*100:.1f}, {hi*100:.1f}] | {imported}/{n} | {fmt(cov)} | {fmt(yield_pct)} |"
        )
    add("")
    add(t["note1"])
    add(t["note2"])
    add("")

    add(t["t2"])
    add("")
    models = sorted({r["model"] for r in rows})
    conds = ["A", "B"]
    add("| Module | " + " | ".join(f"{DISPLAY[m]}-{c}" for m in models for c in conds) + " |")
    add("|" + "---|" * (1 + len(models) * len(conds)))
    for mod in sorted({r["module"] for r in rows}):
        cells = []
        for m in models:
            for c in conds:
                rs = [r for r in rows if r["module"] == mod and r["model"] == m and r["condition"] == c]
                stmt = module_statements.get(mod) or (rs[0]["statements"] or 0 if rs else 0)
                cov = sum(r["covered_lines"] or 0 for r in rs)
                cells.append(f"{100*cov/stmt:.0f}" if stmt else "—")
        add(f"| {mod} | " + " | ".join(cells) + " |")
    add("")

    add(t["t3"])
    add("")
    tax = defaultdict(Counter)
    for r in rows:
        tax[(r["model"], r["condition"])][classify(r, t)] += 1
    kinds = [t["none"], t["assert"], t["import"], t["hang"], t["syntax"], t["other"]]
    kinds = [k for k in kinds if any(tax[key].get(k) for key in tax)] or list(kinds)
    add("| Model / cond. | " + " | ".join(kinds) + " |")
    add("|" + "---|" * (1 + len(kinds)))
    for key in sorted(tax):
        add(f"| {DISPLAY[key[0]]}-{key[1]} | " + " | ".join(str(tax[key].get(k, 0)) for k in kinds) + " |")
    add("")

    add(t["t4"])
    add("")
    add(t["t4_head"])
    add("|---|---|---|---|---|")
    for r in sorted(rows, key=lambda x: (x["model"], x["condition"], x["module"])):
        if r["failure_kind"] == "none":
            continue
        detail = (r.get("failure_detail") or "").replace("|", "\\|")[:110]
        add(f"| {DISPLAY[r['model']]} | {r['condition']} | {r['module']} | {classify(r, t)} | {detail} |")
    add("")

    text = "\n".join(lines)
    (OUT / t["outfile"]).write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
